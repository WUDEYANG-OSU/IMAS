def add_sample_id(frame: pd.DataFrame, sample_id: str) -> pd.DataFrame:
    out = frame.copy()
    if "sample_id" in out.columns:
        out["sample_id"] = str(sample_id)
    else:
        out.insert(0, "sample_id", str(sample_id))
    return out


def load_and_validate_downstream_tables(
    expected_samples: List[str],
) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """
    Load the completed CCI/pseudotime outputs and standardize their schema.

    The eight-sample communication-pseudotime script writes the cluster label
    as ``new_cluster``. The original single-sample five-stage script expects
    ``cluster_norm``. Both names describe the same sample-specific global
    Leiden cluster, so this function creates a canonical ``cluster_norm``
    alias without changing the source files.
    """
    for path in [
        RECEPTOR_TF_SIG_CSV,
        CLUSTER_PT_CSV,
        EDGE_PT_CSV,
    ]:
        if not path.exists():
            raise FileNotFoundError(path)

    signature_df = pd.read_csv(RECEPTOR_TF_SIG_CSV, low_memory=False)
    cluster_pt = pd.read_csv(CLUSTER_PT_CSV, low_memory=False)
    edge_pt = pd.read_csv(EDGE_PT_CSV, low_memory=False)

    # ------------------------------------------------------------------
    # Cluster pseudotime table
    # ------------------------------------------------------------------
    if "sample_id" not in cluster_pt.columns:
        raise KeyError(
            "cluster pseudotime: missing sample_id; available columns="
            f"{cluster_pt.columns.tolist()}"
        )
    cluster_pt["sample_id"] = cluster_pt["sample_id"].astype(str).str.strip()

    cluster_source_col = find_first_existing_col(
        cluster_pt,
        ["cluster_norm", "new_cluster", "cluster_label", "new_leiden"],
    )
    if cluster_source_col is None:
        if "profile_key" not in cluster_pt.columns:
            raise KeyError(
                f"{CLUSTER_PT_CSV.name}: cannot identify the cluster column. "
                "Expected one of cluster_norm/new_cluster/cluster_label/"
                f"new_leiden or profile_key; available={cluster_pt.columns.tolist()}"
            )
        parsed = cluster_pt["profile_key"].astype(str).map(split_profile_key)
        cluster_pt["cluster_norm"] = [item[1] for item in parsed]
        cluster_source_col = "profile_key"
    else:
        cluster_pt["cluster_norm"] = (
            cluster_pt[cluster_source_col]
            .astype(str)
            .map(normalize_cluster_str)
        )

    if "profile_key" not in cluster_pt.columns:
        cluster_pt["profile_key"] = [
            make_profile_key(sample_id, cluster)
            for sample_id, cluster in zip(
                cluster_pt["sample_id"], cluster_pt["cluster_norm"]
            )
        ]
    else:
        cluster_pt["profile_key"] = cluster_pt["profile_key"].astype(str).str.strip()
        expected_profile_keys = np.asarray(
            [
                make_profile_key(sample_id, cluster)
                for sample_id, cluster in zip(
                    cluster_pt["sample_id"], cluster_pt["cluster_norm"]
                )
            ],
            dtype=str,
        )
        mismatch = (
            cluster_pt["profile_key"].to_numpy(dtype=str)
            != expected_profile_keys
        )
        if mismatch.any():
            example = cluster_pt.loc[
                mismatch,
                ["sample_id", "cluster_norm", "profile_key"],
            ].head(5)
            raise ValueError(
                "cluster pseudotime profile_key disagrees with sample_id/"
                "cluster label:\n" + example.to_string(index=False)
            )

    if cluster_pt[["sample_id", "cluster_norm"]].duplicated().any():
        example = cluster_pt.loc[
            cluster_pt[["sample_id", "cluster_norm"]].duplicated(keep=False),
            ["sample_id", "cluster_norm", "profile_key"],
        ].head(10)
        raise ValueError(
            "cluster pseudotime contains duplicate sample-cluster profiles:\n"
            + example.to_string(index=False)
        )

    cluster_labels = validate_eight_sample_labels(
        cluster_pt["sample_id"].unique().tolist(),
        "cluster pseudotime",
    )
    if set(cluster_labels) != set(expected_samples):
        raise ValueError(
            "cluster pseudotime: sample labels differ from Stage-B manifest. "
            f"manifest={expected_samples}; cluster pseudotime={cluster_labels}"
        )

    log(
        "[PT] cluster column standardized:",
        cluster_source_col,
        "-> cluster_norm",
    )
    log("[PT] cluster pseudotime columns:", cluster_pt.columns.tolist())

    # ------------------------------------------------------------------
    # Edge pseudotime table
    # ------------------------------------------------------------------
    if "sample_id" not in edge_pt.columns:
        raise KeyError(
            "edge pseudotime: missing sample_id; available columns="
            f"{edge_pt.columns.tolist()}"
        )
    edge_pt["sample_id"] = edge_pt["sample_id"].astype(str).str.strip()

    # Prefer explicit cluster columns, but derive them from profile keys when
    # reading outputs that only retain sample::cluster identifiers.
    for cluster_col, profile_col in [
        ("sender_cluster", "sender_profile_key"),
        ("receiver_cluster", "receiver_profile_key"),
    ]:
        if cluster_col not in edge_pt.columns:
            if profile_col not in edge_pt.columns:
                raise KeyError(
                    f"{EDGE_PT_CSV.name}: missing both {cluster_col} and "
                    f"{profile_col}; available={edge_pt.columns.tolist()}"
                )
            parsed = edge_pt[profile_col].astype(str).map(split_profile_key)
            edge_pt[cluster_col] = [item[1] for item in parsed]
        edge_pt[cluster_col] = (
            edge_pt[cluster_col].astype(str).map(normalize_cluster_str)
        )

        if profile_col not in edge_pt.columns:
            edge_pt[profile_col] = [
                make_profile_key(sample_id, cluster)
                for sample_id, cluster in zip(
                    edge_pt["sample_id"], edge_pt[cluster_col]
                )
            ]
        else:
            edge_pt[profile_col] = edge_pt[profile_col].astype(str).str.strip()

    edge_labels = sorted(
        set(edge_pt["sample_id"].tolist()),
        key=natural_sort_key,
    )
    unexpected_edge_samples = sorted(
        set(edge_labels).difference(expected_samples),
        key=natural_sort_key,
    )
    excluded_edge_samples = [
        label
        for label in edge_labels
        if extract_sample_number(label) in EXPECTED_EXCLUDED_SAMPLE_NUMBERS
    ]
    if unexpected_edge_samples or excluded_edge_samples:
        raise ValueError(
            "edge pseudotime contains unexpected/excluded samples: "
            f"unexpected={unexpected_edge_samples}; excluded={excluded_edge_samples}"
        )
    missing_edge_samples = sorted(
        set(expected_samples).difference(edge_labels),
        key=natural_sort_key,
    )
    if missing_edge_samples:
        log(
            "[PT][WARN] samples without edge-pseudotime rows:",
            missing_edge_samples,
        )

    sender_key_samples = edge_pt["sender_profile_key"].map(
        lambda value: split_profile_key(value)[0]
    )
    receiver_key_samples = edge_pt["receiver_profile_key"].map(
        lambda value: split_profile_key(value)[0]
    )
    sender_key_clusters = edge_pt["sender_profile_key"].map(
        lambda value: split_profile_key(value)[1]
    )
    receiver_key_clusters = edge_pt["receiver_profile_key"].map(
        lambda value: split_profile_key(value)[1]
    )

    bad_sample = (
        (sender_key_samples.to_numpy(dtype=str) != edge_pt["sample_id"].to_numpy(dtype=str))
        | (receiver_key_samples.to_numpy(dtype=str) != edge_pt["sample_id"].to_numpy(dtype=str))
        | (sender_key_samples.to_numpy(dtype=str) != receiver_key_samples.to_numpy(dtype=str))
    )
    bad_cluster = (
        (sender_key_clusters.to_numpy(dtype=str) != edge_pt["sender_cluster"].to_numpy(dtype=str))
        | (receiver_key_clusters.to_numpy(dtype=str) != edge_pt["receiver_cluster"].to_numpy(dtype=str))
    )
    if bad_sample.any() or bad_cluster.any():
        bad = bad_sample | bad_cluster
        example = edge_pt.loc[
            bad,
            [
                "sample_id",
                "sender_cluster",
                "receiver_cluster",
                "sender_profile_key",
                "receiver_profile_key",
            ],
        ].head(5)
        raise ValueError(
            "Edge sample/cluster columns disagree with profile keys:\n"
            + example.to_string(index=False)
        )

    log("[PT] edge pseudotime columns:", edge_pt.columns.tolist())
    return signature_df, cluster_pt, edge_pt


def run_one_sample(
    sample_id: str,
    manifest: pd.DataFrame,
    genes_vocab: List[str],
    prior_df: pd.DataFrame,
    signature_df: pd.DataFrame,
    cluster_pt_all: pd.DataFrame,
    edge_pt_all: pd.DataFrame,
) -> dict:
    sample_out = OUT_ROOT / safe_name(sample_id)
    sample_out.mkdir(parents=True, exist_ok=True)

    sample = load_integrated_sample(
        manifest=manifest,
        sample_id=sample_id,
        genes_vocab=genes_vocab,
    )
    target_gene = choose_target_gene(TARGET_GENE, sample, genes_vocab)

    cci_df, cci_source = choose_cci_dataframe_for_sample(sample_id)

    cluster_df = (
        cluster_pt_all[
            cluster_pt_all["sample_id"].astype(str) == str(sample_id)
        ]
        .copy()
        .reset_index(drop=True)
    )
    edge_df = (
        edge_pt_all[
            edge_pt_all["sample_id"].astype(str) == str(sample_id)
        ]
        .copy()
        .reset_index(drop=True)
    )

    if len(cluster_df) == 0:
        raise RuntimeError(f"{sample_id}: no cluster pseudotime rows.")
    if len(edge_df) == 0:
        log(
            "[PT][WARN]",
            sample_id,
            "has no edge pseudotime rows; temporal edge annotations will be empty.",
        )

    log("=" * 100)
    log("[SAMPLE]", sample_id)
    log("[CELLS]", sample.n_cells if hasattr(sample, "n_cells") else len(sample.cells))
    log("[TARGET]", target_gene)
    log("[MODE]", STAGE5_MODE)
    log("[CCI SOURCE]", cci_source)
    log("[OUT]", sample_out.resolve())

    # Stage 1.
    stage1_export = add_sample_id(prior_df, sample_id)
    stage1_export.to_csv(
        sample_out / f"{safe_name(target_gene)}_stage1_prior_edges_auto.csv",
        index=False,
    )
    G1 = build_stage1_core_graph(target_gene, prior_df)

    # Stage 2.
    stage2_table = auto_make_stage2_edge_table(
        target_gene=target_gene,
        sample=sample,
        genes_vocab=genes_vocab,
        stage1_nodes=set(G1.nodes()),
        topk_genes=TOPK_STAGE2_GENES,
        target_cell_q=STAGE2_TARGET_CELL_Q,
        min_target_cells=STAGE2_MIN_TARGET_CELLS,
    )
    add_sample_id(stage2_table, sample_id).to_csv(
        sample_out
        / f"{safe_name(target_gene)}_stage2_representation_edges_auto.csv",
        index=False,
    )
    G2 = build_stage2_core_graph_from_stage1(G1, stage2_table)
    stage2_highlight = build_stage2_highlight_edges(G2)

    # Stage 3.
    G3 = nx.DiGraph(G2)
    stage3_ann = build_stage3_annotations(
        target_gene=target_gene,
        core_graph=G3,
        cci_df=cci_df,
        sig_df=signature_df,
    )
    stage3_table = add_sample_id(pd.DataFrame(stage3_ann), sample_id)
    stage3_table["cci_source_file"] = cci_source.name
    stage3_table.to_csv(
        sample_out / f"{safe_name(target_gene)}_stage3_edge_annotations_auto.csv",
        index=False,
    )
    stage3_highlight = build_stage3_highlight_edges(stage3_ann)

    # Stage 4.
    G4 = nx.DiGraph(G3)
    stage4_ann = build_stage4_annotations(
        stage3_ann=stage3_ann,
        cluster_df=cluster_df,
        edge_df=edge_df,
    )
    add_sample_id(pd.DataFrame(stage4_ann), sample_id).to_csv(
        sample_out / f"{safe_name(target_gene)}_stage4_edge_annotations_auto.csv",
        index=False,
    )
    stage4_highlight = build_stage4_highlight_edges(stage4_ann)

    pos = build_incremental_layout(
        G1,
        G2,
        G3,
        G4,
        center_node=target_gene,
        seed=SEED,
    )

    # Draw Stages 1-4 using the original visualization method.
    draw_stage_figure(
        G1,
        pos,
        title=f"Stage 1 — Prior Injection around {target_gene} | {sample_id}",
        subtitle="Initial RNA-TF prior skeleton",
        out_base=sample_out / f"{safe_name(target_gene)}_stage1_prior_injection",
        highlight_edges=None,
        annotations=None,
        stage=1,
    )
    draw_stage_figure(
        G2,
        pos,
        title=f"Stage 2 — Representation Reshaping around {target_gene} | {sample_id}",
        subtitle="Sample-specific expression-enhanced edges on the same prior backbone",
        out_base=sample_out / f"{safe_name(target_gene)}_stage2_representation_reshape",
        highlight_edges=stage2_highlight,
        annotations=None,
        stage=2,
    )
    draw_stage_figure(
        G3,
        pos,
        title=f"Stage 3 — Communication Filtering around {target_gene} | {sample_id}",
        subtitle="Only within-sample communication-supported edges are annotated",
        out_base=sample_out / f"{safe_name(target_gene)}_stage3_communication_filter",
        highlight_edges=stage3_highlight,
        annotations=stage3_ann,
        stage=3,
    )
    draw_stage_figure(
        G4,
        pos,
        title=f"Stage 4 — Temporal Enhancement around {target_gene} | {sample_id}",
        subtitle="Only this sample's communication-pseudotime support is attached",
        out_base=sample_out / f"{safe_name(target_gene)}_stage4_temporal_enhancement",
        highlight_edges=stage4_highlight,
        annotations=stage4_ann,
        stage=4,
    )

    # Stage 5.
    node_expr_df = collect_stage5_node_expression(
        G=G4,
        sample=sample,
        genes_vocab=genes_vocab,
        fallback_value=0.05,
    )
    add_sample_id(node_expr_df, sample_id).to_csv(
        sample_out / f"{safe_name(target_gene)}_stage5_node_expression.csv",
        index=False,
    )

    stage5_edge_df = build_stage5_field_edge_table(
        G2=G4,
        stage3_ann=stage3_ann,
        stage4_ann=stage4_ann,
        node_expr_df=node_expr_df,
        alpha1=STAGE5_A1,
        alpha2=STAGE5_A2,
        alpha3=STAGE5_A3,
        alpha4=STAGE5_A4,
    )
    add_sample_id(stage5_edge_df, sample_id).to_csv(
        sample_out / f"{safe_name(target_gene)}_stage5_field_edges.csv",
        index=False,
    )

    baseline_node_state = build_stage5_node_state(
        node_expr_df=node_expr_df,
        alpha=STAGE5_ALPHA,
        beta=STAGE5_BETA,
        eps=STAGE5_EPS,
    )
    baseline_node_state_final = run_stage5_field_propagation(
        edge_df=stage5_edge_df,
        node_state_df=baseline_node_state,
    )
    add_sample_id(baseline_node_state_final, sample_id).to_csv(
        sample_out / f"{safe_name(target_gene)}_stage5_baseline_node_state.csv",
        index=False,
    )

    perturbed_node_state = apply_stage5_perturbation(
        node_state_df=baseline_node_state,
        target_node=target_gene,
        mode=STAGE5_MODE,
        strength=STAGE5_PERTURB_STRENGTH,
    )
    perturbed_node_state_final = run_stage5_field_propagation(
        edge_df=stage5_edge_df,
        node_state_df=perturbed_node_state,
    )
    add_sample_id(perturbed_node_state_final, sample_id).to_csv(
        sample_out
        / f"{safe_name(target_gene)}_stage5_{STAGE5_MODE}_node_state.csv",
        index=False,
    )

    stage5_baseline_flux_df = compute_edge_flux_from_state(
        edge_df=stage5_edge_df,
        node_state_df=baseline_node_state_final,
    )
    add_sample_id(stage5_baseline_flux_df, sample_id).to_csv(
        sample_out / f"{safe_name(target_gene)}_stage5_baseline_edge_flux.csv",
        index=False,
    )

    stage5_delta_flux_df = compute_stage5_delta_flux(
        edge_df=stage5_edge_df,
        baseline_node_state_final=baseline_node_state_final,
        perturb_node_state_final=perturbed_node_state_final,
    )
    add_sample_id(stage5_delta_flux_df, sample_id).to_csv(
        sample_out
        / f"{safe_name(target_gene)}_stage5_{STAGE5_MODE}_delta_flux.csv",
        index=False,
    )

    G5_baseline = build_stage5_graph_from_edge_table(
        base_graph=G4,
        edge_df=stage5_edge_df,
        node_state_final_df=baseline_node_state_final,
    )
    G5_perturbed = nx.DiGraph(G5_baseline)

    perturbation_map = {
        str(record["node"]): record.to_dict()
        for _, record in perturbed_node_state_final.iterrows()
    }
    baseline_map = {
        str(record["node"]): record.to_dict()
        for _, record in baseline_node_state_final.iterrows()
    }

    for node in G5_perturbed.nodes():
        if node not in perturbation_map:
            continue
        G5_perturbed.nodes[node]["expr_norm"] = float(
            perturbation_map[node].get(
                "expr_norm",
                G5_perturbed.nodes[node].get("expr_norm", 0.05),
            )
        )
        G5_perturbed.nodes[node]["field_strength_final"] = float(
            perturbation_map[node].get("field_strength_final", 0.0)
        )
        G5_perturbed.nodes[node]["susceptibility_final"] = float(
            perturbation_map[node].get("susceptibility_final", 0.0)
        )
        G5_perturbed.nodes[node]["state_final"] = float(
            perturbation_map[node].get("state_final", 0.0)
        )
        G5_perturbed.nodes[node]["delta_state"] = float(
            perturbation_map[node].get("state_final", 0.0)
            - baseline_map.get(node, {}).get("state_final", 0.0)
        )

    pos3d_baseline = build_stage5_3d_layout(
        pos2d=pos,
        node_state_df=baseline_node_state_final,
        z_mode="field_strength_final",
    )

    perturbation_layout_state = perturbed_node_state_final.copy()
    perturbation_layout_state["delta_state"] = (
        perturbed_node_state_final["state_final"].to_numpy(dtype=float)
        - baseline_node_state_final["state_final"].to_numpy(dtype=float)
    )
    pos3d_perturbation = build_stage5_3d_layout_from_delta(
        pos2d=pos,
        node_state_df=perturbation_layout_state,
    )

    draw_stage5_3d_figures(
        G_baseline=G5_baseline,
        G_perturbed=G5_perturbed,
        pos3d_baseline=pos3d_baseline,
        pos3d_perturb=pos3d_perturbation,
        edge_df_baseline=stage5_edge_df,
        delta_flux_df=stage5_delta_flux_df,
        out_base_baseline=(
            sample_out
            / f"{safe_name(target_gene)}_stage5_physics_integration_3d"
        ),
        out_base_compare=(
            sample_out
            / f"{safe_name(target_gene)}_stage5_{STAGE5_MODE}_response_compare_3d"
        ),
        target_gene=target_gene,
        mode=STAGE5_MODE,
    )

    delta_state = perturbed_node_state_final["state_final"].to_numpy(dtype=float) - (
        baseline_node_state_final["state_final"].to_numpy(dtype=float)
    )

    return {
        "sample_id": str(sample_id),
        "target_gene": str(target_gene),
        "n_cells": int(len(sample.cells)),
        "cci_source_file": str(cci_source),
        "n_cci_rows": int(len(cci_df)),
        "n_cluster_pseudotime_rows": int(len(cluster_df)),
        "n_edge_pseudotime_rows": int(len(edge_df)),
        "n_stage1_nodes": int(G1.number_of_nodes()),
        "n_stage1_edges": int(G1.number_of_edges()),
        "n_stage2_nodes": int(G2.number_of_nodes()),
        "n_stage2_edges": int(G2.number_of_edges()),
        "n_stage3_annotations": int(len(stage3_ann)),
        "n_stage4_annotations": int(len(stage4_ann)),
        "n_stage5_nodes": int(len(baseline_node_state_final)),
        "n_stage5_edges": int(len(stage5_edge_df)),
        "max_abs_delta_state": float(np.max(np.abs(delta_state))) if len(delta_state) else 0.0,
        "mean_abs_delta_state": float(np.mean(np.abs(delta_state))) if len(delta_state) else 0.0,
        "output_dir": str(sample_out),
        "status": "ok",
    }


def main():
    for path in [
        FRONTIER_CKPT,
        RNA_MANIFEST,
        GLOBAL_GENE_VOCAB,
        GLOBAL_TF_VOCAB,
        PRIORS_DIR,
        RECEPTOR_TF_SIG_CSV,
        CLUSTER_PT_CSV,
        EDGE_PT_CSV,
    ]:
        if not path.exists():
            raise FileNotFoundError(path)

    manifest, sample_labels = load_completed_stageb_manifest()
    genes_vocab = read_vocab_txt(GLOBAL_GENE_VOCAB)

    signature_df, cluster_pt_all, edge_pt_all = (
        load_and_validate_downstream_tables(sample_labels)
    )

    prior_df = load_tf_gene_prior_edges(
        priors_dir=PRIORS_DIR,
        tf_vocab_txt=GLOBAL_TF_VOCAB,
        gene_vocab_txt=GLOBAL_GENE_VOCAB,
        prefer_full_with_decay=PREFER_FULL_WITH_DECAY,
        decay_after_256=DECAY_AFTER_256,
        decay_mode=DECAY_MODE,
    )

    summaries = []
    failures = []

    for sample_id in sample_labels:
        try:
            summary = run_one_sample(
                sample_id=sample_id,
                manifest=manifest,
                genes_vocab=genes_vocab,
                prior_df=prior_df,
                signature_df=signature_df,
                cluster_pt_all=cluster_pt_all,
                edge_pt_all=edge_pt_all,
            )
            summaries.append(summary)
            pd.DataFrame(summaries).to_csv(
                RUN_SUMMARY_TSV,
                sep="\t",
                index=False,
            )
        except Exception as exc:
            failure = {
                "sample_id": str(sample_id),
                "error_type": type(exc).__name__,
                "error": str(exc),
            }
            failures.append(failure)
            pd.DataFrame(failures).to_csv(
                FAILED_SAMPLES_TSV,
                sep="\t",
                index=False,
            )
            log("[ERROR]", sample_id, type(exc).__name__, str(exc))
            if FAIL_FAST:
                raise

    if summaries:
        pd.DataFrame(summaries).to_csv(
            RUN_SUMMARY_TSV,
            sep="\t",
            index=False,
        )
    if failures:
        pd.DataFrame(failures).to_csv(
            FAILED_SAMPLES_TSV,
            sep="\t",
            index=False,
        )

    log("=" * 100)
    log("[DONE] successful samples:", len(summaries))
    log("[DONE] failed samples:", len(failures))
    log("[DONE] outputs:", OUT_ROOT.resolve())
    log("[SUMMARY]", RUN_SUMMARY_TSV)
    if failures:
        log("[FAILED]", FAILED_SAMPLES_TSV)


if __name__ == "__main__":
    main()
