def main() -> None:
    plt.rcParams.update(
        {
            "font.family": "DejaVu Sans",
            "font.size": 8.5,
            "axes.linewidth": 0.9,
            "figure.facecolor": "white",
            "axes.facecolor": "white",
            "pdf.fonttype": 42,
            "ps.fonttype": 42,
            "svg.fonttype": "none",
        }
    )

    score_path = discover_score_path()
    output_directory = score_path.parent

    log("[SCORE TABLE]", score_path)
    log("[OUTPUT]", output_directory)

    table = pd.read_csv(score_path)

    required_columns = [
        "sid",
        "rid",
        "CCI_cluster_position",
        "pretrain_RNA_TF_support",
        "pretrain_RNA_RE_support",
        "pretrain_integrated_SOD2_support",
        "after_RNA_TF_support",
        "after_RNA_RE_support",
        "after_integrated_SOD2_support",
        "signed_MLTD_gain",
        "pretrain_SOD2_score_z",
        "after_SOD2_score_z",
        "foundation_adjusted_MLTD_z",
    ]

    missing = [
        column
        for column in required_columns
        if column not in table.columns
    ]

    if missing:
        raise KeyError(
            f"The score table is missing required columns: {missing}"
        )

    table = table.reset_index(drop=True)

    audit = build_direction_audit(table)

    raw_bootstrap = stratified_bootstrap_correlations(
        table=table,
        x_column="pretrain_integrated_SOD2_support",
        y_column="after_integrated_SOD2_support",
        n_bootstrap=N_GLOBAL_BOOTSTRAP,
        seed=BOOTSTRAP_SEED,
        metric_label="Raw integrated support",
    )

    rank_bootstrap = stratified_bootstrap_correlations(
        table=table,
        x_column="pretrain_SOD2_score_z",
        y_column="after_SOD2_score_z",
        n_bootstrap=N_GLOBAL_BOOTSTRAP,
        seed=BOOTSTRAP_SEED + 1,
        metric_label="Within-cluster rank-normalized support",
    )

    global_bootstrap = pd.concat(
        [
            raw_bootstrap,
            rank_bootstrap,
        ],
        axis=0,
        ignore_index=True,
    )

    global_summary = build_global_summary(
        table=table,
        bootstrap_table=global_bootstrap,
    )

    per_cluster, cluster_bootstrap = build_per_cluster_summary(
        table=table,
    )

    all_bootstrap = pd.concat(
        [
            global_bootstrap,
            cluster_bootstrap,
        ],
        axis=0,
        ignore_index=True,
        sort=False,
    )

    audit_path = (
        output_directory
        / "SOD2_foundation_vs_MLTD_direction_audit.csv"
    )

    global_path = (
        output_directory
        / "SOD2_foundation_vs_MLTD_global_correlation_summary.csv"
    )

    cluster_path = (
        output_directory
        / "SOD2_foundation_vs_MLTD_per_cluster_correlations.csv"
    )

    bootstrap_path = (
        output_directory
        / "SOD2_foundation_vs_MLTD_bootstrap_correlations.csv.gz"
    )

    audit.to_csv(audit_path, index=False)
    global_summary.to_csv(global_path, index=False)
    per_cluster.to_csv(cluster_path, index=False)
    all_bootstrap.to_csv(
        bootstrap_path,
        index=False,
        compression="gzip",
    )

    for path in [
        audit_path,
        global_path,
        cluster_path,
        bootstrap_path,
    ]:
        log("[SAVE]", path)

    plot_qc_figure(
        table=table,
        audit=audit,
        global_summary=global_summary,
        per_cluster=per_cluster,
        output_directory=output_directory,
    )

    raw_rho = float(
        global_summary.loc[
            global_summary["analysis"]
            == "Raw integrated support",
            "spearman_rho",
        ].iloc[0]
    )

    rank_rho = float(
        global_summary.loc[
            global_summary["analysis"]
            == "Within-cluster rank-normalized support",
            "spearman_rho",
        ].iloc[0]
    )

    between_rho = float(
        global_summary.loc[
            global_summary["analysis"]
            == "Between-cluster raw means",
            "spearman_rho",
        ].iloc[0]
    )

    median_cluster_rho = float(
        per_cluster["raw_spearman_rho"].median()
    )

    simpson_flag = bool(
        np.isfinite(raw_rho)
        and np.isfinite(rank_rho)
        and np.sign(raw_rho) != np.sign(rank_rho)
    )

    manifest = {
        "score_table": str(score_path),
        "n_cells": int(table.shape[0]),
        "n_clusters": int(
            table["CCI_cluster_position"].nunique()
        ),
        "support_direction_definition": (
            "Both pretrain and after integrated scores are positive "
            "target-support alignments computed as the geometric mean of "
            "nonnegative RNA-TF and RNA-RE target support. Larger values "
            "therefore indicate stronger SOD2 support in both model states."
        ),
        "global_raw_Spearman": raw_rho,
        "global_within_cluster_rank_Spearman": rank_rho,
        "between_cluster_mean_Spearman": between_rho,
        "median_per_cluster_Spearman": median_cluster_rho,
        "possible_Simpson_sign_reversal_raw_vs_rank": simpson_flag,
        "interpretation_rule": {
            "rank_negative_and_most_clusters_negative": (
                "Supports genuine within-cluster cell re-ranking."
            ),
            "raw_and_rank_opposite_signs": (
                "Cluster-level scale contributes to the global raw result; "
                "interpret the within-cluster rank result as the primary "
                "cell-reordering statistic."
            ),
            "between_cluster_positive_but_rank_negative": (
                "Classic cross-level opposition: cluster means are conserved "
                "while cells are reordered within clusters."
            ),
        },
        "bootstrap": {
            "global_repeats": int(N_GLOBAL_BOOTSTRAP),
            "per_cluster_repeats": int(N_CLUSTER_BOOTSTRAP),
            "global_sampling": (
                "Stratified bootstrap preserving each CCI cluster's size."
            ),
        },
    }

    manifest_path = (
        output_directory
        / "SOD2_foundation_vs_MLTD_score_QC_manifest.json"
    )

    with open(
        manifest_path,
        "w",
        encoding="utf-8",
    ) as handle:
        json.dump(
            manifest,
            handle,
            indent=2,
            ensure_ascii=False,
        )

    log("[SAVE]", manifest_path)
    log("[DONE]", "Foundation-versus-MLTD score QC completed.")


if __name__ == "__main__":
    main()
