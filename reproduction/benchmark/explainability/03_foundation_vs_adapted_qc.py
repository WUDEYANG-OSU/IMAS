"""
Validate the interpretation of the pan-cancer-foundation versus CRC-adapted
MLTD SOD2 score comparison.

This script does NOT rerun the model. It reads the cached cell-level score
table generated by:

    compare_SOD2_pan_cancer_foundation_vs_MLTD_refinement_full_standalone.py

and performs three requested checks:

1. Direction consistency
   - pretrain and after scores are both positive target-support quantities;
   - integrated support equals sqrt(max(RNA-TF, 0) * max(RNA-RE, 0));
   - signed_MLTD_gain equals after support minus pretrain support;
   - saved within-cluster rank-normalized scores are reproduced exactly.

2. Raw versus rank-normalized association
   - global Pearson and Spearman correlations;
   - top-20% Jaccard overlap;
   - stratified-bootstrap confidence intervals.

3. Cluster-resolved association / Simpson's-paradox check
   - per-CCI-cluster Spearman correlations with bootstrap confidence intervals;
   - pooled within-cluster association;
   - between-cluster mean association;
   - median and cell-count-weighted per-cluster association.

Main output:
    SOD2_foundation_vs_MLTD_score_QC.png/.pdf/.svg

Tables:
    SOD2_foundation_vs_MLTD_direction_audit.csv
    SOD2_foundation_vs_MLTD_global_correlation_summary.csv
    SOD2_foundation_vs_MLTD_per_cluster_correlations.csv
    SOD2_foundation_vs_MLTD_bootstrap_correlations.csv.gz
    SOD2_foundation_vs_MLTD_score_QC_manifest.json
"""

