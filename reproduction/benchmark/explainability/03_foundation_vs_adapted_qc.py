def discover_score_path() -> Path:
    env_value = os.environ.get(
        "SOD2_FOUNDATION_MLTD_SCORE_CSV",
        "",
    ).strip()

    if env_value:
        candidate = Path(env_value).expanduser().resolve()
        if candidate.exists():
            return candidate

    direct_candidates = [
        root / SCORE_FILENAME
        for root in DEFAULT_SEARCH_ROOTS
    ]

    for candidate in direct_candidates:
        if candidate.exists():
            return candidate.resolve()

    for root in DEFAULT_SEARCH_ROOTS:
        if not root.exists():
            continue

        try:
            candidates = list(
                root.rglob(SCORE_FILENAME)
            )
        except Exception:
            candidates = []

        if candidates:
            # Prefer the expected pan-cancer-versus-MLTD subdirectory.
            candidates = sorted(
                candidates,
                key=lambda path: (
                    "SOD2_pan_cancer_foundation_vs_MLTD_refinement"
                    not in str(path),
                    len(str(path)),
                ),
            )
            return candidates[0].resolve()

    checked = "\n".join(
        str(candidate)
        for candidate in direct_candidates
    )

    raise FileNotFoundError(
        "Could not locate the cached SOD2 cell-score table.\n"
        "Set SOD2_FOUNDATION_MLTD_SCORE_CSV or place the file at one of:\n"
        f"{checked}"
    )


