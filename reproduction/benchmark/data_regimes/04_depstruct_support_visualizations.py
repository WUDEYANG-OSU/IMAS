def load_all_cell_tables(out_root: Path) -> tuple[pd.DataFrame, str]:
    tables = []
    support_col_name = None
    for ds in DATASETS:
        for reg in REGIMES:
            f = out_root / f"{ds}_{reg}_cell_structure_scores_with_DepStruct.csv"
            if not f.exists():
                print("[WARN missing]", f)
                continue
            df = pd.read_csv(f)
            support_col = pick_col(df, ["depstruct_score_cell", "DepStruct", "depstruct_score"])
            if support_col is None:
                raise ValueError(f"Cannot find support score column in {f.name}")
            if support_col_name is None:
                support_col_name = support_col
            df = df.copy()
            df["dataset"] = ds
            df["data_regime"] = reg
            df["support_score"] = pd.to_numeric(df[support_col], errors="coerce")
            tables.append(df)
            print("[LOAD]", f, "rows=", len(df))
    if len(tables) == 0:
        raise RuntimeError("No *_cell_structure_scores_with_DepStruct.csv files found.")
    all_df = pd.concat(tables, axis=0, ignore_index=True)
    all_df = all_df.replace([np.inf, -np.inf], np.nan)
    all_df = all_df.dropna(subset=["support_score"])
    all_df["support_score"] = all_df["support_score"].clip(lower=0.0, upper=1.0)
    return all_df, support_col_name


