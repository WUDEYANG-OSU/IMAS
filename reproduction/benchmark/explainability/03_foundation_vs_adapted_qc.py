def build_global_summary(
    table: pd.DataFrame,
    bootstrap_table: pd.DataFrame,
) -> pd.DataFrame:
    definitions = [
        (
            "Raw integrated support",
            "pretrain_integrated_SOD2_support",
            "after_integrated_SOD2_support",
        ),
        (
            "Within-cluster rank-normalized support",
            "pretrain_SOD2_score_z",
            "after_SOD2_score_z",
        ),
    ]

    rows = []

    for label, x_column, y_column in definitions:
        x = table[x_column].to_numpy(dtype=np.float64)
        y = table[y_column].to_numpy(dtype=np.float64)

        pearson, pearson_p = safe_pearson(x, y)
        spearman, spearman_p = safe_spearman(x, y)
        jaccard = jaccard_top_fraction(
            x,
            y,
            TOP_FRACTION,
        )

        bootstrap = bootstrap_table[
            bootstrap_table["analysis"] == label
        ]

        rows.append(
            {
                "analysis": label,
                "n_cells": int(table.shape[0]),
                "pearson_r": pearson,
                "pearson_P": pearson_p,
                "pearson_CI_low": float(
                    bootstrap["pearson_r"].quantile(0.025)
                ),
                "pearson_CI_high": float(
                    bootstrap["pearson_r"].quantile(0.975)
                ),
                "spearman_rho": spearman,
                "spearman_P": spearman_p,
                "spearman_CI_low": float(
                    bootstrap["spearman_rho"].quantile(0.025)
                ),
                "spearman_CI_high": float(
                    bootstrap["spearman_rho"].quantile(0.975)
                ),
                "top_20_percent_Jaccard": jaccard,
            }
        )

    cluster_means = (
        table.groupby(
            "CCI_cluster_position",
            sort=True,
        )[
            [
                "pretrain_integrated_SOD2_support",
                "after_integrated_SOD2_support",
            ]
        ]
        .mean()
        .reset_index()
    )

    between_rho, between_p = safe_spearman(
        cluster_means[
            "pretrain_integrated_SOD2_support"
        ],
        cluster_means[
            "after_integrated_SOD2_support"
        ],
    )

    rows.append(
        {
            "analysis": "Between-cluster raw means",
            "n_cells": int(cluster_means.shape[0]),
            "pearson_r": safe_pearson(
                cluster_means[
                    "pretrain_integrated_SOD2_support"
                ],
                cluster_means[
                    "after_integrated_SOD2_support"
                ],
            )[0],
            "pearson_P": safe_pearson(
                cluster_means[
                    "pretrain_integrated_SOD2_support"
                ],
                cluster_means[
                    "after_integrated_SOD2_support"
                ],
            )[1],
            "pearson_CI_low": np.nan,
            "pearson_CI_high": np.nan,
            "spearman_rho": between_rho,
            "spearman_P": between_p,
            "spearman_CI_low": np.nan,
            "spearman_CI_high": np.nan,
            "top_20_percent_Jaccard": np.nan,
        }
    )

    return pd.DataFrame(rows)


def build_per_cluster_summary(
    table: pd.DataFrame,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    rows = []
    bootstrap_rows = []

    for cluster_index, (
        cluster_position,
        group,
    ) in enumerate(
        table.groupby(
            "CCI_cluster_position",
            sort=True,
        )
    ):
        group = group.copy()

        if group.shape[0] < int(MIN_CLUSTER_CELLS):
            continue

        cluster_name = (
            str(group["CCI_cluster_name"].iloc[0])
            if "CCI_cluster_name" in group.columns
            else f"Cluster {int(cluster_position)}"
        )

        raw_pre = group[
            "pretrain_integrated_SOD2_support"
        ].to_numpy(dtype=np.float64)

        raw_after = group[
            "after_integrated_SOD2_support"
        ].to_numpy(dtype=np.float64)

        rank_pre = group[
            "pretrain_SOD2_score_z"
        ].to_numpy(dtype=np.float64)

        rank_after = group[
            "after_SOD2_score_z"
        ].to_numpy(dtype=np.float64)

        raw_spearman, raw_p = safe_spearman(
            raw_pre,
            raw_after,
        )

        rank_spearman, rank_p = safe_spearman(
            rank_pre,
            rank_after,
        )

        raw_pearson, raw_pearson_p = safe_pearson(
            raw_pre,
            raw_after,
        )

        rank_pearson, rank_pearson_p = safe_pearson(
            rank_pre,
            rank_after,
        )

        cluster_bootstrap = cluster_bootstrap_spearman(
            group=group,
            x_column="pretrain_integrated_SOD2_support",
            y_column="after_integrated_SOD2_support",
            n_bootstrap=N_CLUSTER_BOOTSTRAP,
            seed=(
                BOOTSTRAP_SEED
                + 10000
                + cluster_index
                * 101
            ),
        )

        for repeat, value in enumerate(
            cluster_bootstrap.tolist()
        ):
            bootstrap_rows.append(
                {
                    "analysis": "Per-cluster raw Spearman",
                    "CCI_cluster_position": int(cluster_position),
                    "CCI_cluster_name": cluster_name,
                    "bootstrap_repeat": int(repeat),
                    "spearman_rho": float(value),
                }
            )

        rows.append(
            {
                "CCI_cluster_position": int(cluster_position),
                "CCI_cluster_name": cluster_name,
                "n_cells": int(group.shape[0]),
                "raw_pearson_r": raw_pearson,
                "raw_pearson_P": raw_pearson_p,
                "raw_spearman_rho": raw_spearman,
                "raw_spearman_P": raw_p,
                "raw_spearman_CI_low": float(
                    np.nanquantile(
                        cluster_bootstrap,
                        0.025,
                    )
                ),
                "raw_spearman_CI_high": float(
                    np.nanquantile(
                        cluster_bootstrap,
                        0.975,
                    )
                ),
                "rank_normalized_pearson_r": rank_pearson,
                "rank_normalized_pearson_P": rank_pearson_p,
                "rank_normalized_spearman_rho": rank_spearman,
                "rank_normalized_spearman_P": rank_p,
                "raw_minus_rank_spearman": float(
                    raw_spearman
                    - rank_spearman
                ),
                "top_20_percent_Jaccard": jaccard_top_fraction(
                    raw_pre,
                    raw_after,
                    TOP_FRACTION,
                ),
                "pretrain_raw_mean": float(np.mean(raw_pre)),
                "after_raw_mean": float(np.mean(raw_after)),
            }
        )

    return (
        pd.DataFrame(rows),
        pd.DataFrame(bootstrap_rows),
    )


