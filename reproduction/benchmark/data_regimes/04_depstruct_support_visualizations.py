def _count_existing_regime_csvs(out_root: Path, dataset_prefix: str) -> int:
    """Count how many regime CSVs exist for one concrete file prefix."""
    n = 0
    for reg in REGIMES:
        f = out_root / f"{dataset_prefix}_{reg}_cell_structure_scores_with_DepStruct.csv"
        if f.exists():
            n += 1
    return n


def _scan_existing_dataset_prefixes(out_root: Path) -> list[str]:
    """Infer dataset prefixes from real files under OUT_ROOT."""
    prefixes = set()
    suffix = "_cell_structure_scores_with_DepStruct.csv"
    for f in out_root.glob(f"*{suffix}"):
        name = f.name
        for reg in REGIMES:
            tail = f"_{reg}{suffix}"
            if name.endswith(tail):
                prefixes.add(name[: -len(tail)])
                break
    return sorted(prefixes)


def resolve_requested_datasets(out_root: Path) -> list[str]:
    """
    Resolve canonical dataset names to the actual prefixes present on disk.

    This prevents an empty read when local files are named slightly differently,
    e.g. Osteosarcoma vs Osteosarcoma-Tissue. CRC/Glioma are simply read from
    existing CSVs; no model is recomputed in this script.
    """
    existing_prefixes = _scan_existing_dataset_prefixes(out_root)
    print("[AVAILABLE DATASET PREFIXES]", existing_prefixes)
    resolved = []
    for requested in DATASETS_REQUESTED:
        aliases = DATASET_ALIASES.get(requested, [requested])
        # Prefer aliases with all three regimes, but accept partial availability and warn.
        scored = [(alias, _count_existing_regime_csvs(out_root, alias)) for alias in aliases]
        scored = sorted(scored, key=lambda x: x[1], reverse=True)
        best_alias, best_n = scored[0] if scored else (requested, 0)
        if best_n == 0:
            print(f"[WARN dataset missing] {requested}: no regime CSV found for aliases={aliases}")
            continue
        missing_regs = [
            reg for reg in REGIMES
            if not (out_root / f"{best_alias}_{reg}_cell_structure_scores_with_DepStruct.csv").exists()
        ]
        if missing_regs:
            print(f"[WARN partial dataset] {requested} -> {best_alias}: missing regimes={missing_regs}")
        else:
            print(f"[DATASET RESOLVED] {requested} -> {best_alias}")
        resolved.append(best_alias)
    if not resolved:
        raise RuntimeError(
            "No requested dataset CSVs were found. Existing dataset prefixes under OUT_ROOT are: "
            + ", ".join(existing_prefixes)
        )
    return resolved


