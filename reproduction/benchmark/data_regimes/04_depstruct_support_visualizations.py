# 8. FIGURE 05: BOXPLOT + STRIP
# ============================================================

def plot_boxstrip(cell_df: pd.DataFrame, tests_df: pd.DataFrame, out_root: Path):
    fig, axes = plt.subplots(1, len(DATASETS), figsize=(figure_width(4.8, 12.2), 5.2), facecolor="white", squeeze=False)
    axes = axes[0]
    rng = np.random.default_rng(123)
    for ax, ds in zip(axes, DATASETS):
        ds_sub = cell_df[cell_df["dataset"] == ds].copy()
        groups = []
        for reg in REGIMES:
            vals = ds_sub.loc[ds_sub["data_regime"] == reg, "support_score"].dropna().astype(float).values
            groups.append(vals)
        bp = ax.boxplot(groups, positions=np.arange(1, len(REGIMES)+1), widths=0.42, patch_artist=True, showfliers=False)
        for patch, reg in zip(bp['boxes'], REGIMES):
            patch.set_facecolor(REGIME_COLOR[reg])
            patch.set_alpha(0.22)
            patch.set_edgecolor(REGIME_COLOR[reg])
        for med in bp['medians']:
            med.set_color('black')
            med.set_linewidth(1.6)

        for i, (reg, vals) in enumerate(zip(REGIMES, groups), start=1):
            if len(vals) == 0:
                continue
            if len(vals) > MAX_POINTS_BOXSTRIP:
                pick = rng.choice(len(vals), size=MAX_POINTS_BOXSTRIP, replace=False)
                vals_plot = vals[pick]
            else:
                vals_plot = vals
            x = np.full(len(vals_plot), i, dtype=float) + jitter(len(vals_plot), scale=0.10, seed=100+i)
            ax.scatter(x, vals_plot, s=5, alpha=0.25, color=REGIME_COLOR[reg], edgecolor='none')

        ds_tests = tests_df[tests_df["dataset"] == ds].copy()
        pair_specs = [
            (1, 2, ds_tests[(ds_tests["group_a"] == "multiomic_only") & (ds_tests["group_b"] == "mixed")]),
            (1, 3, ds_tests[(ds_tests["group_a"] == "multiomic_only") & (ds_tests["group_b"] == "scrna_only")]),
            (2, 3, ds_tests[(ds_tests["group_a"] == "mixed") & (ds_tests["group_b"] == "scrna_only")]),
        ]
        ymax = max(1.0, float(np.nanmax([np.nanmax(g) if len(g) else 0 for g in groups])))
        heights = [ymax + 0.05, ymax + 0.12, ymax + 0.19]
        for (x1, x2, row), h in zip(pair_specs, heights):
            q = float(row["mannwhitney_qvalue"].iloc[0]) if len(row) else np.nan
            ax.plot([x1, x1, x2, x2], [h - 0.01, h, h, h - 0.01], color="black", lw=0.8)
            ax.text((x1 + x2) / 2, h + 0.005, p_to_stars(q), ha="center", va="bottom", fontsize=8)

        ax.set_xlim(0.5, len(REGIMES) + 0.5)
        ax.set_ylim(0, max(1.0, ymax + 0.27))
        ax.set_xticks(np.arange(1, len(REGIMES)+1))
        ax.set_xticklabels([REGIME_LABEL[r] for r in REGIMES])
        ax.set_ylabel("Dependent-structure support")
        ax.set_title(nice_dataset_label(ds), fontweight="bold")
        ax.grid(axis='y', alpha=0.15, linewidth=0.5)
    fig.suptitle("Dependent-structure support: boxplot + strip view", fontweight="bold", y=1.05)
    savefig_multi(fig, out_root / "05_depstruct_support_boxstrip")

plot_boxstrip(cell_df2, tests_df, OUT_ROOT)

