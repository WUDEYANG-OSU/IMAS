def safe_pearson(
    x: np.ndarray,
    y: np.ndarray,
) -> tuple[float, float]:
    x = np.asarray(x, dtype=np.float64)
    y = np.asarray(y, dtype=np.float64)

    finite = np.isfinite(x) & np.isfinite(y)
    x = x[finite]
    y = y[finite]

    if (
        x.size < 3
        or np.std(x) <= 1e-12
        or np.std(y) <= 1e-12
    ):
        return np.nan, np.nan

    result = stats.pearsonr(x, y)
    return float(result.statistic), float(result.pvalue)


def safe_spearman(
    x: np.ndarray,
    y: np.ndarray,
) -> tuple[float, float]:
    x = np.asarray(x, dtype=np.float64)
    y = np.asarray(y, dtype=np.float64)

    finite = np.isfinite(x) & np.isfinite(y)
    x = x[finite]
    y = y[finite]

    if (
        x.size < 3
        or np.std(x) <= 1e-12
        or np.std(y) <= 1e-12
    ):
        return np.nan, np.nan

    result = stats.spearmanr(x, y)
    return float(result.statistic), float(result.pvalue)


def jaccard_top_fraction(
    x: np.ndarray,
    y: np.ndarray,
    fraction: float,
) -> float:
    x = np.asarray(x, dtype=np.float64)
    y = np.asarray(y, dtype=np.float64)

    finite = np.isfinite(x) & np.isfinite(y)
    indices = np.where(finite)[0]

    if indices.size == 0:
        return np.nan

    n_top = max(
        1,
        int(
            math.ceil(
                indices.size
                * float(fraction)
            )
        ),
    )

    x_order = indices[
        np.argsort(
            x[indices]
        )[::-1][:n_top]
    ]

    y_order = indices[
        np.argsort(
            y[indices]
        )[::-1][:n_top]
    ]

    x_set = set(map(int, x_order.tolist()))
    y_set = set(map(int, y_order.tolist()))

    return float(
        len(x_set & y_set)
        / max(
            len(x_set | y_set),
            1,
        )
    )


def recompute_cluster_rank_z(
    table: pd.DataFrame,
    value_column: str,
) -> np.ndarray:
    percentile = table.groupby(
        "CCI_cluster_position",
        sort=True,
    )[value_column].rank(
        method="average",
        pct=True,
    )

    clipped = np.clip(
        percentile.to_numpy(dtype=np.float64),
        1e-4,
        1.0 - 1e-4,
    )

    return stats.norm.ppf(clipped)


def stratified_bootstrap_correlations(
    table: pd.DataFrame,
    x_column: str,
    y_column: str,
    n_bootstrap: int,
    seed: int,
    metric_label: str,
) -> pd.DataFrame:
    rng = np.random.default_rng(int(seed))

    cluster_indices = {
        int(cluster): group.index.to_numpy(dtype=np.int64)
        for cluster, group in table.groupby(
            "CCI_cluster_position",
            sort=True,
        )
    }

    rows = []

    for repeat in range(int(n_bootstrap)):
        sampled_parts = []

        for _, indices in cluster_indices.items():
            sampled_parts.append(
                rng.choice(
                    indices,
                    size=indices.size,
                    replace=True,
                )
            )

        sampled = np.concatenate(sampled_parts)

        x = table.loc[
            sampled,
            x_column,
        ].to_numpy(dtype=np.float64)

        y = table.loc[
            sampled,
            y_column,
        ].to_numpy(dtype=np.float64)

        pearson, _ = safe_pearson(x, y)
        spearman, _ = safe_spearman(x, y)

        rows.append(
            {
                "analysis": metric_label,
                "bootstrap_repeat": int(repeat),
                "pearson_r": pearson,
                "spearman_rho": spearman,
            }
        )

    return pd.DataFrame(rows)


def cluster_bootstrap_spearman(
    group: pd.DataFrame,
    x_column: str,
    y_column: str,
    n_bootstrap: int,
    seed: int,
) -> np.ndarray:
    rng = np.random.default_rng(int(seed))

    x = group[x_column].to_numpy(dtype=np.float64)
    y = group[y_column].to_numpy(dtype=np.float64)

    output = np.full(
        int(n_bootstrap),
        np.nan,
        dtype=np.float64,
    )

    for repeat in range(int(n_bootstrap)):
        sampled = rng.integers(
            0,
            group.shape[0],
            size=group.shape[0],
        )

        output[repeat] = safe_spearman(
            x[sampled],
            y[sampled],
        )[0]

    return output


