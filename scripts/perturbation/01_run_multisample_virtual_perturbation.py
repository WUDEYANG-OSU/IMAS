def natural_sort_key(value: str):
    parts = re.split(r"(\d+)", str(value))
    return [int(part) if part.isdigit() else part.lower() for part in parts]


def extract_sample_number(sample_id: str) -> Optional[int]:
    text = str(sample_id).strip().lower()
    patterns = [
        r"(?:sample|sam|s)[-_ ]*0*(\d+)(?:\D|$)",
        r"(?:^|\D)0*(\d+)(?:\D|$)",
    ]
    for pattern in patterns:
        match = re.search(pattern, text)
        if match:
            return int(match.group(1))
    return None


def validate_eight_sample_labels(sample_labels: List[str], source_name: str) -> List[str]:
    labels = sorted({str(x).strip() for x in sample_labels if str(x).strip()}, key=natural_sort_key)
    if len(labels) != EXPECTED_SAMPLE_COUNT:
        raise ValueError(
            f"{source_name}: expected {EXPECTED_SAMPLE_COUNT} samples, "
            f"found {len(labels)}: {labels}"
        )
    excluded_hits = [
        label
        for label in labels
        if extract_sample_number(label) in EXPECTED_EXCLUDED_SAMPLE_NUMBERS
    ]
    if excluded_hits:
        raise ValueError(
            f"{source_name}: excluded Sample-7 is present: {excluded_hits}"
        )
    return labels


def choose_cci_dataframe_for_sample(sample_id: str) -> Tuple[pd.DataFrame, Path]:
    """
    Prefer the TF-kept CCI table for this sample, then high-confidence, then all.
    The fallback is evaluated per sample rather than globally.
    """
    existing = []
    for path in [CCI_TFKEPT_CSV, CCI_HIGHCONF_CSV, CCI_ALL_CSV]:
        if not path.exists():
            continue
        existing.append(path)
        frame = pd.read_csv(path, low_memory=False)
        if "sample_id" not in frame.columns:
            raise KeyError(f"{path.name}: missing sample_id")
        frame["sample_id"] = frame["sample_id"].astype(str).str.strip()
        sub = frame[frame["sample_id"] == str(sample_id)].copy().reset_index(drop=True)
        if len(sub) > 0:
            log("[CCI]", sample_id, "using", path.name, "rows=", len(sub))
            return sub, path

    if not existing:
        raise FileNotFoundError(
            "No eight-sample CCI interaction table exists. Tried:\n"
            + "\n".join(
                str(path)
                for path in [CCI_TFKEPT_CSV, CCI_HIGHCONF_CSV, CCI_ALL_CSV]
            )
        )

    # Return a schema-preserving empty sample slice from the broadest existing
    # table. Stage 3 will then contain no communication annotations, while
    # Stages 1, 2 and 5 remain executable.
    fallback_path = existing[-1]
    frame = pd.read_csv(fallback_path, low_memory=False)
    if "sample_id" not in frame.columns:
        raise KeyError(f"{fallback_path.name}: missing sample_id")
    empty = frame.iloc[0:0].copy()
    log(
        "[CCI][WARN]",
        sample_id,
        "has no rows in TF-kept/high-confidence/all tables; "
        "Stage 3/4 communication annotations will be empty.",
    )
    return empty, fallback_path


def edge_width(w: float, low=1.0, high=4.2) -> float:
    if not np.isfinite(w):
        return low
    x = math.log1p(max(0.0, float(w)))
    return low + (high - low) * min(1.0, x / math.log1p(10.0))


def cosine_sim(a: np.ndarray, b: np.ndarray) -> float:
    a = np.asarray(a, float)
    b = np.asarray(b, float)

    na = np.linalg.norm(a)
    nb = np.linalg.norm(b)

    if na < 1e-12 or nb < 1e-12:
        return 0.0

    return float(np.dot(a, b) / (na * nb))


def _safe_minmax_scale(values: Dict, floor: float = 0.0, ceil: float = 1.0) -> Dict:
    if len(values) == 0:
        return {}

    xs = np.array(list(values.values()), dtype=float)
    finite = np.isfinite(xs)

    if finite.sum() == 0:
        return {k: floor for k in values}

    lo = float(np.nanmin(xs[finite]))
    hi = float(np.nanmax(xs[finite]))

    if hi - lo < 1e-12:
        mid = 0.5 * (floor + ceil)
        return {k: mid for k in values}

    out = {}
    for k, v in values.items():
        if not np.isfinite(v):
            out[k] = floor
        else:
            z = (float(v) - lo) / (hi - lo)
            out[k] = floor + (ceil - floor) * z

    return out


def _safe_log1p_scale(values: Dict) -> Dict:
    tmp = {}
    for k, v in values.items():
        vv = 0.0 if (not np.isfinite(v)) else max(0.0, float(v))
        tmp[k] = math.log1p(vv)
    return _safe_minmax_scale(tmp)


