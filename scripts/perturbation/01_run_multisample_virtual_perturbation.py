def log(*args):
    print(*args, flush=True)


def read_vocab_txt(path: Path) -> List[str]:
    out = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            s = line.strip()
            if s:
                out.append(s)
    return out


def safe_name(x: str, n: int = 80) -> str:
    return re.sub(r"[^A-Za-z0-9_\-\.]+", "_", str(x))[:n]


def normalize_cluster_str(x: str) -> str:
    s = str(x).strip()
    if s.startswith("C") and s[1:].isdigit():
        return s[1:]
    return s


def normalize_gene_name(x: str) -> str:
    return str(x).strip() if x is not None else ""


def norm_barcode(x: str) -> str:
    x = str(x)
    return x.split("::", 1)[-1] if "::" in x else x


def make_profile_key(sample_id: str, cluster: str) -> str:
    return f"{str(sample_id).strip()}::{normalize_cluster_str(cluster)}"


def split_profile_key(profile_key: str) -> Tuple[str, str]:
    value = str(profile_key).strip()
    if "::" not in value:
        raise ValueError(f"Invalid profile_key without '::': {value}")
    sample_id, cluster = value.rsplit("::", 1)
    return sample_id, normalize_cluster_str(cluster)


