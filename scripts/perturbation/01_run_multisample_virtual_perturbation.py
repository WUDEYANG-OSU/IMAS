def auto_make_stage2_edge_table(
    target_gene: str,
    sample: Sample,
    genes_vocab: list[str],
    stage1_nodes: Set[str],
    topk_genes: int = 12,
    target_cell_q: float = 0.85,
    min_target_cells: int = 10,
) -> pd.DataFrame:
    """
    Counts-based Stage2:
    - choose target-high cells by target_gene expression quantile
    - fallback to top min_target_cells if too few cells pass the quantile
    - compute log1p counts in target-high cells
    - rank genes by mean_log1p_expr * (1 + log1p(1 + 10 * presence))
    - prioritize genes already present in Stage1 nodes
    """
    gene2tid = {g: i for i, g in enumerate(genes_vocab)}

    if target_gene not in gene2tid:
        raise KeyError(f"{target_gene} not found in global gene vocab")

    target_tid = gene2tid[target_gene]

    if target_tid not in sample.train2rna:
        raise KeyError(f"{target_gene} matched global vocab, but not found in sample.train2rna")

    target_rna_col = sample.train2rna[target_tid]
    target_expr = get_counts_col_dense(sample, target_rna_col)

    finite_mask = np.isfinite(target_expr)
    x = target_expr[finite_mask]

    if x.size == 0:
        raise RuntimeError(f"{target_gene} expression is all non-finite in sample {sample.sid}")

    thr = float(np.quantile(x, target_cell_q))
    target_rows = np.where(target_expr >= thr)[0]

    if target_rows.size < min_target_cells:
        order = np.argsort(np.nan_to_num(target_expr, nan=-1.0))[::-1]
        target_rows = order[:min(min_target_cells, len(order))]

    counts_mm = np.load(sample.counts_path, mmap_mode="r")
    global_target_rows = sample.row_indices[target_rows]
    X = np.asarray(counts_mm[global_target_rows, :], dtype=np.float32)
    X = np.log1p(np.clip(X, 0.0, None))

    mean_expr = X.mean(axis=0).astype(np.float32)

    items = []

    for local_gidx, score in enumerate(mean_expr.tolist()):
        tid = int(sample.ext2train[local_gidx])

        if tid < 0 or tid >= len(genes_vocab):
            continue

        gene_name = str(genes_vocab[tid])

        if gene_name == target_gene:
            continue

        presence = float((X[:, local_gidx] > 0).mean())
        final_score = float(score) * (1.0 + np.log1p(1.0 + 10.0 * presence))

        items.append((gene_name, final_score, float(score), float(presence)))

    items_sorted = sorted(
        items,
        key=lambda x: (
            0 if x[0] in stage1_nodes else 1,
            -x[1],
            -x[2],
            -x[3],
            x[0],
        ),
    )[:topk_genes]

    rows = []

    for gene_name, final_score, mean_log1p_expr, presence in items_sorted:
        rows.append({
            "src": target_gene,
            "dst": gene_name,
            "weight": float(final_score),
            "mean_log1p_expr_in_target_cells": float(mean_log1p_expr),
            "presence_in_target_cells": float(presence),
            "stage2_mode": "counts_based",
        })

    return pd.DataFrame(rows)


def build_stage2_core_graph_from_stage1(G1: nx.DiGraph, stage2_df: pd.DataFrame) -> nx.DiGraph:
    G = nx.DiGraph(G1)

    for _, r in stage2_df.iterrows():
        s = str(r["src"])
        d = str(r["dst"])
        w = float(r["weight"])

        if d not in G:
            G.add_node(d, kind="gene")

        ww = max(0.8, min(5.0, np.log1p(w)))

        if not G.has_edge(s, d):
            G.add_edge(
                s,
                d,
                weight=ww,
                edge_type="representation_similarity",
            )
        else:
            G[s][d]["stage2_boost"] = float(ww)

    return G


