def plot_stacked_strata(strata_df: pd.DataFrame, tests_df: pd.DataFrame, out_root: Path):
    fig, axes = plt.subplots(1, len(DATASETS), figsize=(figure_width(4.8, 12.2), 5.1), facecolor="white", squeeze=False)
    axes = axes[0]

    for ax, ds in zip(axes, DATASETS):
        sub = strata_df[strata_df["dataset"] == ds].copy()
        x = np.arange(len(REGIMES))
        bottoms = np.zeros(len(REGIMES), dtype=float)
        for lab in STRATA_LABELS:
            vals = []
            for reg in REGIMES:
                tmp = sub[(sub["data_regime"] == reg) & (sub["support_stratum"].astype(str) == lab)]
                vals.append(float(tmp["fraction"].iloc[0]) if len(tmp) else 0.0)
            ax.bar(x, vals, bottom=bottoms, color=STRATA_COLORS[lab], edgecolor="white", linewidth=0.8, label=lab)
            bottoms += np.asarray(vals)

        # annotate high-support fraction on top
        ds_summary = summary_df[summary_df["dataset"] == ds].set_index("data_regime")
        for i, reg in enumerate(REGIMES):
            if reg in ds_summary.index:
                hf = float(ds_summary.loc[reg, "high_support_fraction"])
                ax.text(i, 1.02, f"High={hf:.1%}", ha="center", va="bottom", fontsize=8)

        # add MW q-value stars for high-support related overall support diff comparisons above bars
        ds_tests = tests_df[tests_df["dataset"] == ds].copy()
        # multiomic vs mixed
        pair_specs = [
            (0, 1, ds_tests[(ds_tests["group_a"] == "multiomic_only") & (ds_tests["group_b"] == "mixed")]),
            (0, 2, ds_tests[(ds_tests["group_a"] == "multiomic_only") & (ds_tests["group_b"] == "scrna_only")]),
            (1, 2, ds_tests[(ds_tests["group_a"] == "mixed") & (ds_tests["group_b"] == "scrna_only")]),
        ]
        heights = [1.08, 1.15, 1.22]
        for (x1, x2, row), h in zip(pair_specs, heights):
            q = float(row["mannwhitney_qvalue"].iloc[0]) if len(row) else np.nan
            ax.plot([x1, x1, x2, x2], [h - 0.01, h, h, h - 0.01], color="black", lw=0.8)
            ax.text((x1 + x2) / 2, h + 0.005, p_to_stars(q), ha="center", va="bottom", fontsize=8)

        ax.set_xticks(x)
        ax.set_xticklabels([REGIME_LABEL[r] for r in REGIMES], rotation=0)
        ax.set_ylim(0, 1.28)
        ax.set_ylabel("Fraction of cells")
        ax.set_title(nice_dataset_label(ds), fontweight="bold")
        ax.grid(axis="y", alpha=0.15, linewidth=0.5)

    handles = [Line2D([0], [0], color=STRATA_COLORS[lab], lw=8, label=lab) for lab in STRATA_LABELS]
    fig.legend(handles=handles, loc="upper center", ncol=4, frameon=False, bbox_to_anchor=(0.5, 1.03))
    fig.suptitle("Support-strata composition of dependent-structure support", fontweight="bold", y=1.10)
    savefig_multi(fig, out_root / "03_depstruct_support_strata_stacked")

