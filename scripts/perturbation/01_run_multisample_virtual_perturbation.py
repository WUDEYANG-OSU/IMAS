def unit_normal(p0: np.ndarray, p1: np.ndarray):
    v = p1 - p0
    nv = np.linalg.norm(v)

    if nv < 1e-9:
        return np.array([0.0, 1.0])

    v = v / nv
    return np.array([-v[1], v[0]])


