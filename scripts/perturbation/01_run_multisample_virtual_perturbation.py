def to_wsl_path(x: str | Path) -> str:
    text = str(x).replace("\\", "/")
    match = re.match(r"^([A-Za-z]):/(.*)$", text)
    if match:
        return f"/mnt/{match.group(1).lower()}/{match.group(2)}"
    return text


def load_completed_stageb_manifest() -> Tuple[pd.DataFrame, List[str]]:
    if not RNA_MANIFEST.exists():
        raise FileNotFoundError(
            "Cannot find the manifest written by the completed eight-sample "
            f"Stage-B run:\n{RNA_MANIFEST}"
        )

    manifest = pd.read_csv(RNA_MANIFEST, sep="\t", low_memory=False)
    required = [
        "cell_id",
        "sample_id",
        "row_index",
        "counts_npy",
        "meta_npz",
    ]
    for column in required:
        if column not in manifest.columns:
            raise KeyError(f"{RNA_MANIFEST.name}: missing column {column}")

    manifest = manifest.copy()
    manifest["cell_id"] = manifest["cell_id"].astype(str)
    manifest["sample_id"] = manifest["sample_id"].astype(str).str.strip()
    manifest["row_index"] = pd.to_numeric(
        manifest["row_index"], errors="raise"
    ).astype(np.int64)

    for column in ["counts_npy", "depth_npy", "log1p_npy", "meta_npz"]:
        if column in manifest.columns:
            manifest[column] = manifest[column].map(
                lambda value: to_wsl_path(value)
                if pd.notna(value) and str(value).strip()
                else ""
            )

    manifest = (
        manifest.sort_values("row_index")
        .reset_index(drop=True)
    )

    sample_labels = validate_eight_sample_labels(
        manifest["sample_id"].unique().tolist(),
        "Stage-B manifest",
    )

    if manifest["cell_id"].duplicated().any():
        # cell_id can theoretically repeat between biological samples, so only
        # the composite sample/cell key must be unique.
        composite = (
            manifest["sample_id"].astype(str)
            + "::"
            + manifest["cell_id"].astype(str)
        )
        if composite.duplicated().any():
            raise ValueError("Stage-B manifest contains duplicate sample/cell keys.")

    counts_paths = sorted(
        {
            str(value)
            for value in manifest["counts_npy"].tolist()
            if str(value).strip()
        }
    )
    meta_paths = sorted(
        {
            str(value)
            for value in manifest["meta_npz"].tolist()
            if str(value).strip()
        }
    )
    if len(counts_paths) != 1:
        raise ValueError(
            "The completed Stage-B manifest must reference one shared counts "
            f"matrix; found: {counts_paths}"
        )
    if len(meta_paths) != 1:
        raise ValueError(
            "The completed Stage-B manifest must reference one shared metadata "
            f"NPZ; found: {meta_paths}"
        )

    counts_path = Path(counts_paths[0])
    meta_path = Path(meta_paths[0])
    if not counts_path.exists():
        raise FileNotFoundError(counts_path)
    if not meta_path.exists():
        raise FileNotFoundError(meta_path)

    counts_mm = np.load(counts_path, mmap_mode="r")
    if counts_mm.ndim != 2:
        raise ValueError("Shared RNA counts matrix must be two-dimensional.")
    rows = manifest["row_index"].to_numpy(dtype=np.int64)
    if rows.min(initial=0) < 0 or rows.max(initial=-1) >= counts_mm.shape[0]:
        raise IndexError(
            "Manifest row_index values are outside the shared counts matrix."
        )

    meta_npz = np.load(meta_path, allow_pickle=True)
    if "gene_names" not in meta_npz:
        raise KeyError(f"{meta_path.name}: missing gene_names")
    gene_names = np.asarray(meta_npz["gene_names"]).astype(str)
    if counts_mm.shape[1] != len(gene_names):
        raise ValueError(
            f"Counts genes {counts_mm.shape[1]} != metadata genes {len(gene_names)}"
        )

    log("[MANIFEST]", RNA_MANIFEST)
    log("[COUNTS]", counts_path, tuple(counts_mm.shape))
    log("[META]", meta_path)
    log("[SAMPLES]", sample_labels)
    log(
        manifest.groupby("sample_id", sort=True)
        .size()
        .rename("n_cells")
        .to_string()
    )
    return manifest, sample_labels


def load_integrated_sample(
    manifest: pd.DataFrame,
    sample_id: str,
    genes_vocab: List[str],
) -> Sample:
    group = (
        manifest[manifest["sample_id"].astype(str) == str(sample_id)]
        .copy()
        .sort_values("row_index")
        .reset_index(drop=True)
    )
    if len(group) == 0:
        raise ValueError(f"No manifest rows found for sample_id={sample_id}")

    counts_paths = sorted(set(group["counts_npy"].astype(str)))
    meta_paths = sorted(set(group["meta_npz"].astype(str)))
    if len(counts_paths) != 1 or len(meta_paths) != 1:
        raise ValueError(
            f"{sample_id}: inconsistent counts/meta paths in Stage-B manifest."
        )

    counts_path = Path(counts_paths[0])
    meta_path = Path(meta_paths[0])
    counts_mm = np.load(counts_path, mmap_mode="r")
    meta_npz = np.load(meta_path, allow_pickle=True)
    gene_names = np.asarray(meta_npz["gene_names"]).astype(str)

    cells = group["cell_id"].astype(str).map(norm_barcode).to_numpy(dtype=object)
    row_indices = group["row_index"].to_numpy(dtype=np.int64)

    gene2i_vocab = {gene: index for index, gene in enumerate(genes_vocab)}
    ext2train = np.full((len(gene_names),), -1, dtype=np.int64)
    train2rna: dict[int, int] = {}
    for local_gene_index, gene_name in enumerate(gene_names):
        normalized = normalize_gene_name(gene_name)
        if normalized in gene2i_vocab:
            train_id = int(gene2i_vocab[normalized])
            ext2train[local_gene_index] = train_id
            if train_id not in train2rna:
                train2rna[train_id] = local_gene_index

    barcode_to_local_row = {
        str(barcode): index
        for index, barcode in enumerate(cells.tolist())
    }

    return Sample(
        sid=str(sample_id),
        cells=cells,
        row_indices=row_indices,
        counts_path=counts_path,
        counts_shape=tuple(counts_mm.shape),
        gene_names=gene_names,
        ext2train=ext2train,
        train2rna=train2rna,
        bc2rid=barcode_to_local_row,
    )


def get_counts_col_dense(sample: Sample, gene_idx_in_sample: int) -> np.ndarray:
    counts_mm = np.load(sample.counts_path, mmap_mode="r")
    values = np.asarray(
        counts_mm[sample.row_indices, int(gene_idx_in_sample)]
    ).reshape(-1)
    return values.astype(np.float32, copy=False)


def choose_target_gene(
    target_gene: str,
    sample: Sample,
    genes_vocab: List[str],
) -> str:
    target_gene = str(target_gene).strip()
    gene_set_sample = set(sample.gene_names.astype(str).tolist())
    gene_set_vocab = set(genes_vocab)

    if target_gene in gene_set_sample and target_gene in gene_set_vocab:
        return target_gene

    if not ALLOW_TARGET_FALLBACK:
        raise ValueError(
            f"TARGET_GENE={target_gene} not found in both sample gene_names "
            f"and global vocabulary for {sample.sid}. Change TARGET_GENE or "
            "set ALLOW_TARGET_FALLBACK=True."
        )

    counts_mm = np.load(sample.counts_path, mmap_mode="r")
    sample_counts = np.asarray(
        counts_mm[sample.row_indices, :],
        dtype=np.float32,
    )
    mean_expression = sample_counts.mean(axis=0)
    order = np.argsort(mean_expression)[::-1]

    for local_gene_index in order[:5000]:
        gene = str(sample.gene_names[int(local_gene_index)])
        if gene in gene_set_vocab:
            log("[WARN]", sample.sid, "fallback target:", target_gene, "->", gene)
            return gene

    raise RuntimeError(f"{sample.sid}: cannot find a fallback target gene.")


