def plot_umap_landscape_if_available(cell_df: pd.DataFrame, out_root: Path):
    if not {"umap_1", "umap_2"}.issubset(set(cell_df.columns)):
        print("[SKIP] UMAP landscape: umap_1/umap_2 not found")
        return
    fig, axes = plt.subplots(len(DATASETS), len(REGIMES), figsize=(4.15 * len(REGIMES), figure_height(3.6, 7.6)), facecolor="white", squeeze=False)
    sc_for_colorbar = None
    for i, ds in enumerate(DATASETS):
        for j, reg in enumerate(REGIMES):
            ax = axes[i, j]
            sub = cell_df[(cell_df["dataset"] == ds) & (cell_df["data_regime"] == reg)].copy()
            if len(sub) == 0:
                ax.axis('off')
                continue
            sub = sub.dropna(subset=["umap_1", "umap_2", "support_score"])
            if len(sub) == 0:
                ax.axis('off')
                continue
            sc = ax.scatter(
                sub["umap_1"], sub["umap_2"],
                c=sub["support_score"], cmap="Reds", s=3, alpha=0.65, linewidths=0, rasterized=True,
                vmin=0, vmax=1,
            )
            sc_for_colorbar = sc
            ax.set_xticks([])
            ax.set_yticks([])
            for spine in ax.spines.values():
                spine.set_visible(False)
            title = f"{REGIME_LABEL[reg]}"
            subtitle = summary_df[(summary_df['dataset'] == ds) & (summary_df['data_regime'] == reg)]
            med = float(subtitle['median_support'].iloc[0]) if len(subtitle) else np.nan
            ax.set_title(f"{title}\nmedian={med:.3f}", fontsize=10, fontweight='bold')
            if j == 0:
                ax.text(-0.06, 0.5, nice_dataset_label(ds), transform=ax.transAxes, rotation=90,
                        ha='right', va='center', fontsize=11, fontweight='bold')
    if sc_for_colorbar is None:
        print("[SKIP] UMAP landscape colorbar: no valid points")
        plt.close(fig)
        return
    cbar = fig.colorbar(sc_for_colorbar, ax=axes.ravel().tolist(), shrink=0.78, pad=0.01)
    cbar.set_label("Dependent-structure support")
    fig.suptitle("Optional manifold landscape of dependent-structure support", fontweight='bold', y=1.02)
    fig.subplots_adjust(wspace=0.05, hspace=0.22)
    savefig_multi(fig, out_root / "06_depstruct_support_umap_landscape")

plot_umap_landscape_if_available(cell_df2, OUT_ROOT)

