def savefig_multi(fig, stem: Path):
    for ext in ["png", "pdf", "svg"]:
        out = stem.with_suffix(f".{ext}")
        fig.savefig(out, dpi=400 if ext == "png" else None, bbox_inches="tight", facecolor="white")
        print("[SAVE]", out)
    plt.close(fig)


def pick_col(df: pd.DataFrame, aliases) -> str | None:
    low_map = {c.lower(): c for c in df.columns}
    for a in aliases:
        if a in df.columns:
            return a
        if a.lower() in low_map:
            return low_map[a.lower()]
    return None


def nice_dataset_label(x: str) -> str:
    sx = str(x)
    return DATASET_DISPLAY_LABEL.get(sx, sx.replace("-Tissue", ""))


def jitter(n, scale=0.08, seed=42):
    rng = np.random.default_rng(seed)
    return rng.uniform(-scale, scale, n)


def bh_fdr(pvals):
    pvals = np.asarray(pvals, dtype=float)
    n = len(pvals)
    if n == 0:
        return pvals
    order = np.argsort(np.where(np.isnan(pvals), np.inf, pvals))
    ranked = pvals[order]
    q = np.full(n, np.nan, dtype=float)
    prev = 1.0
    for i in range(n - 1, -1, -1):
        p = ranked[i]
        if not np.isfinite(p):
            continue
        rank = i + 1
        val = min(prev, p * n / rank)
        q[order[i]] = val
        prev = val
    return q


def p_to_stars(p):
    if not np.isfinite(p):
        return "n.a."
    if p < 1e-4:
        return "****"
    if p < 1e-3:
        return "***"
    if p < 1e-2:
        return "**"
    if p < 5e-2:
        return "*"
    return "n.s."

