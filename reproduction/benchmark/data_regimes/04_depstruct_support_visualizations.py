def make_support_summaries(cell_df: pd.DataFrame):
    work = cell_df.copy()
    work["support_stratum"] = pd.cut(
        work["support_score"],
        bins=STRATA_BINS,
        labels=STRATA_LABELS,
        include_lowest=True,
        right=False,
    )

    strata = (
        work.groupby(["dataset", "data_regime", "support_stratum"], as_index=False)
        .size()
        .rename(columns={"size": "n_cells"})
    )
    totals = (
        work.groupby(["dataset", "data_regime"], as_index=False)
        .size()
        .rename(columns={"size": "total_cells"})
    )
    strata = strata.merge(totals, on=["dataset", "data_regime"], how="left")
    strata["fraction"] = strata["n_cells"] / strata["total_cells"]

    summary = (
        work.groupby(["dataset", "data_regime"], as_index=False)
        .agg(
            n_cells=("support_score", "size"),
            mean_support=("support_score", "mean"),
            median_support=("support_score", "median"),
            q25_support=("support_score", lambda x: np.nanpercentile(x, 25)),
            q75_support=("support_score", lambda x: np.nanpercentile(x, 75)),
            high_support_fraction=("support_score", lambda x: float(np.mean(np.asarray(x) >= HIGH_SUPPORT_THRESHOLD))),
            low_support_fraction=("support_score", lambda x: float(np.mean(np.asarray(x) < LOW_SUPPORT_THRESHOLD))),
        )
    )

    # pairwise tests within each dataset
    pairs = [("multiomic_only", "mixed"), ("multiomic_only", "scrna_only"), ("mixed", "scrna_only")]
    test_rows = []
    for ds in DATASETS:
        ds_sub = work[work["dataset"] == ds].copy()
        for a, b in pairs:
            xa = ds_sub.loc[ds_sub["data_regime"] == a, "support_score"].dropna().astype(float).values
            xb = ds_sub.loc[ds_sub["data_regime"] == b, "support_score"].dropna().astype(float).values
            if len(xa) == 0 or len(xb) == 0:
                ks_p = mw_p = np.nan
                delta_mean = delta_median = np.nan
                high_a = high_b = low_a = low_b = np.nan
            else:
                try:
                    ks_p = float(ks_2samp(xa, xb, alternative="two-sided", mode="auto").pvalue)
                except Exception:
                    ks_p = np.nan
                try:
                    mw_p = float(mannwhitneyu(xa, xb, alternative="two-sided").pvalue)
                except Exception:
                    mw_p = np.nan
                delta_mean = float(np.nanmean(xa) - np.nanmean(xb))
                delta_median = float(np.nanmedian(xa) - np.nanmedian(xb))
                high_a = float(np.mean(xa >= HIGH_SUPPORT_THRESHOLD))
                high_b = float(np.mean(xb >= HIGH_SUPPORT_THRESHOLD))
                low_a = float(np.mean(xa < LOW_SUPPORT_THRESHOLD))
                low_b = float(np.mean(xb < LOW_SUPPORT_THRESHOLD))
            test_rows.append({
                "dataset": ds,
                "group_a": a,
                "group_b": b,
                "ks_pvalue": ks_p,
                "mannwhitney_pvalue": mw_p,
                "delta_mean_support": delta_mean,
                "delta_median_support": delta_median,
                "high_support_fraction_a": high_a,
                "high_support_fraction_b": high_b,
                "delta_high_support_fraction": high_a - high_b if np.isfinite(high_a) and np.isfinite(high_b) else np.nan,
                "low_support_fraction_a": low_a,
                "low_support_fraction_b": low_b,
                "delta_low_support_fraction": low_a - low_b if np.isfinite(low_a) and np.isfinite(low_b) else np.nan,
            })
    tests = pd.DataFrame(test_rows)
    # BH separately for each dataset and each test family
    tests["ks_qvalue"] = np.nan
    tests["mannwhitney_qvalue"] = np.nan
    for ds in tests["dataset"].unique():
        mask = tests["dataset"] == ds
        tests.loc[mask, "ks_qvalue"] = bh_fdr(tests.loc[mask, "ks_pvalue"].values)
        tests.loc[mask, "mannwhitney_qvalue"] = bh_fdr(tests.loc[mask, "mannwhitney_pvalue"].values)
    return work, strata, summary, tests


