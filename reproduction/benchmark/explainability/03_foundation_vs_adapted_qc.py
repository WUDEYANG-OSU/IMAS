def build_direction_audit(
    table: pd.DataFrame,
) -> pd.DataFrame:
    pre_tf = table[
        "pretrain_RNA_TF_support"
    ].to_numpy(dtype=np.float64)

    pre_re = table[
        "pretrain_RNA_RE_support"
    ].to_numpy(dtype=np.float64)

    pre_integrated = table[
        "pretrain_integrated_SOD2_support"
    ].to_numpy(dtype=np.float64)

    after_tf = table[
        "after_RNA_TF_support"
    ].to_numpy(dtype=np.float64)

    after_re = table[
        "after_RNA_RE_support"
    ].to_numpy(dtype=np.float64)

    after_integrated = table[
        "after_integrated_SOD2_support"
    ].to_numpy(dtype=np.float64)

    signed_gain = table[
        "signed_MLTD_gain"
    ].to_numpy(dtype=np.float64)

    expected_pre_integrated = np.sqrt(
        np.maximum(pre_tf, 0.0)
        * np.maximum(pre_re, 0.0)
    )

    expected_after_integrated = np.sqrt(
        np.maximum(after_tf, 0.0)
        * np.maximum(after_re, 0.0)
    )

    expected_gain = (
        after_integrated
        - pre_integrated
    )

    recomputed_pretrain_z = recompute_cluster_rank_z(
        table,
        "pretrain_integrated_SOD2_support",
    )

    recomputed_after_z = recompute_cluster_rank_z(
        table,
        "after_integrated_SOD2_support",
    )

    rows = []

    def add_check(
        name: str,
        observed: float,
        threshold: float | None,
        criterion: str,
        passed: bool,
    ) -> None:
        rows.append(
            {
                "check": name,
                "observed_value": float(observed),
                "threshold": (
                    float(threshold)
                    if threshold is not None
                    else np.nan
                ),
                "criterion": criterion,
                "status": (
                    "PASS"
                    if passed
                    else "WARN"
                ),
            }
        )

    pre_formula_error = float(
        np.nanmax(
            np.abs(
                pre_integrated
                - expected_pre_integrated
            )
        )
    )

    after_formula_error = float(
        np.nanmax(
            np.abs(
                after_integrated
                - expected_after_integrated
            )
        )
    )

    gain_error = float(
        np.nanmax(
            np.abs(
                signed_gain
                - expected_gain
            )
        )
    )

    pre_rank_error = float(
        np.nanmax(
            np.abs(
                table[
                    "pretrain_SOD2_score_z"
                ].to_numpy(dtype=np.float64)
                - recomputed_pretrain_z
            )
        )
    )

    after_rank_error = float(
        np.nanmax(
            np.abs(
                table[
                    "after_SOD2_score_z"
                ].to_numpy(dtype=np.float64)
                - recomputed_after_z
            )
        )
    )

    tolerance = 1e-5

    add_check(
        "Pretrain integrated-support formula error",
        pre_formula_error,
        tolerance,
        "max |saved - sqrt(max(TF,0)*max(RE,0))|",
        pre_formula_error <= tolerance,
    )

    add_check(
        "After integrated-support formula error",
        after_formula_error,
        tolerance,
        "max |saved - sqrt(max(TF,0)*max(RE,0))|",
        after_formula_error <= tolerance,
    )

    add_check(
        "Signed-gain identity error",
        gain_error,
        tolerance,
        "max |signed_gain - (after - pretrain)|",
        gain_error <= tolerance,
    )

    add_check(
        "Pretrain rank-normalization reproduction error",
        pre_rank_error,
        tolerance,
        "max |saved z - recomputed within-cluster rank z|",
        pre_rank_error <= tolerance,
    )

    add_check(
        "After rank-normalization reproduction error",
        after_rank_error,
        tolerance,
        "max |saved z - recomputed within-cluster rank z|",
        after_rank_error <= tolerance,
    )

    add_check(
        "Pretrain integrated support negative fraction",
        float(np.mean(pre_integrated < -tolerance)),
        0.0,
        "fraction should be zero because support is a positive alignment",
        float(np.mean(pre_integrated < -tolerance)) == 0.0,
    )

    add_check(
        "After integrated support negative fraction",
        float(np.mean(after_integrated < -tolerance)),
        0.0,
        "fraction should be zero because support is a positive alignment",
        float(np.mean(after_integrated < -tolerance)) == 0.0,
    )

    for state, integrated, tf_support, re_support in [
        (
            "Pretrain",
            pre_integrated,
            pre_tf,
            pre_re,
        ),
        (
            "After",
            after_integrated,
            after_tf,
            after_re,
        ),
    ]:
        tf_rho = safe_spearman(
            integrated,
            tf_support,
        )[0]

        re_rho = safe_spearman(
            integrated,
            re_support,
        )[0]

        add_check(
            f"{state} integrated versus RNA-TF Spearman",
            tf_rho,
            None,
            "positive correlation expected for higher=stronger support",
            bool(np.isfinite(tf_rho) and tf_rho > 0),
        )

        add_check(
            f"{state} integrated versus RNA-RE Spearman",
            re_rho,
            None,
            "positive correlation expected for higher=stronger support",
            bool(np.isfinite(re_rho) and re_rho > 0),
        )

    audit = pd.DataFrame(rows)

    if STRICT_FORMULA_QC:
        strict_checks = audit[
            audit["check"].isin(
                [
                    "Pretrain integrated-support formula error",
                    "After integrated-support formula error",
                    "Signed-gain identity error",
                    "Pretrain rank-normalization reproduction error",
                    "After rank-normalization reproduction error",
                    "Pretrain integrated support negative fraction",
                    "After integrated support negative fraction",
                ]
            )
        ]

        if not bool(
            (strict_checks["status"] == "PASS").all()
        ):
            raise RuntimeError(
                "One or more strict score-direction/formula checks failed.\n"
                f"{strict_checks.to_string(index=False)}"
            )

    return audit


