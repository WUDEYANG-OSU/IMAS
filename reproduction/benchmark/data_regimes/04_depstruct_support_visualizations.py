def plot_retention_curves(cell_df: pd.DataFrame, out_root: Path):
    thresholds = np.linspace(0, 1, 201)
    fig, axes = plt.subplots(1, len(DATASETS), figsize=(figure_width(4.8, 12.2), 4.8), facecolor="white", squeeze=False)
    axes = axes[0]
    for ax, ds in zip(axes, DATASETS):
        sub = cell_df[cell_df["dataset"] == ds].copy()
        for reg in REGIMES:
            x = sub.loc[sub["data_regime"] == reg, "support_score"].dropna().astype(float).values
            if len(x) == 0:
                continue
            y = [np.mean(x >= t) for t in thresholds]
            ax.plot(thresholds, y, lw=2.0, color=REGIME_COLOR[reg], label=REGIME_LABEL[reg])
        ax.axvline(HIGH_SUPPORT_THRESHOLD, color="#999999", lw=0.8, ls="--")
        ax.set_xlim(0, 1)
        ax.set_ylim(0, 1)
        ax.set_xlabel("Support threshold")
        ax.set_ylabel("Fraction of cells with support ≥ threshold")
        ax.set_title(nice_dataset_label(ds), fontweight="bold")
        ax.grid(alpha=0.18, linewidth=0.5)
    handles = [Line2D([0], [0], color=REGIME_COLOR[r], lw=2.2, label=REGIME_LABEL[r]) for r in REGIMES]
    fig.legend(handles=handles, loc="upper center", ncol=3, frameon=False, bbox_to_anchor=(0.5, 1.04))
    fig.suptitle("Retention of high dependent-structure support across thresholds", fontweight="bold", y=1.10)
    savefig_multi(fig, out_root / "02_depstruct_support_retention_curves")

